        let dir = tempfile::tempdir().unwrap();
        let root = dir.path().join("data");
        std::fs::create_dir_all(&root).unwrap();
        let target = dir.path().join("dotfiles-cola");
        std::fs::write(&target, marked("complete -F _cola cola\n")).unwrap();
        let link = root.join("cola");
        std::os::unix::fs::symlink(&target, &link).unwrap();

        let script = marked("complete -F _cola cola\n");
