    /// A read-only marked completion is refused by the real install, and the
    /// preview reports that same refusal.
    #[cfg(unix)]
    #[test]
    fn a_read_only_completion_is_refused_by_both_paths() {
        use std::os::unix::fs::PermissionsExt;

        // root bypasses the permission bits, so this can only be observed as a
        // normal user (the CI runner is one).
        if rustix::process::geteuid().as_raw() == 0 {
            return;
        }
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("cola");
        std::fs::write(&path, format!("{MARKER}\nold\n")).unwrap();
        std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o444)).unwrap();

        let script = marked("complete -F _cola cola\n");
        let preview = install(path.clone(), dir.path(), &script, true).unwrap_err();
        assert!(preview.to_string().contains("not writable"), "{preview}");
        let real = install(path, dir.path(), &script, false).unwrap_err();
        assert!(real.to_string().contains("not writable"), "{real}");
    }

